void logo_data_draw(void)
{
    VDP_loadTileData(tile_logo[0], TILE_LOGO_BASE, LOGO_TILE_COUNT, DMA);
    PAL_setPalette(PAL0, pal_logo, DMA);

    /* Tile zero in this bank is the logo artwork's flat near-black surround.
     * Fill both planes with it explicitly: VDP_clearTextArea() uses the system
     * font's space tile, whose VRAM is intentionally reused by later art banks
     * and can become a striped pattern after a soft reset. */
    VDP_fillTileMapRect(BG_B,
        TILE_ATTR_FULL(PAL0, 0, FALSE, FALSE, TILE_LOGO_BASE), 0, 0, 40, 28);
    VDP_fillTileMapRect(BG_A,
        TILE_ATTR_FULL(PAL0, 0, FALSE, FALSE, TILE_LOGO_BASE), 0, 0, 40, 28);

    u16 offX = (40 - LOGO_TILES_W) / 2;
    u16 offY = (28 - LOGO_TILES_H) / 2;
    u16 row, col;
    for (row = 0; row < LOGO_TILES_H; row++)
    {
        for (col = 0; col < LOGO_TILES_W; col++)
        {
            u16 t = logo_tilemap[row][col];
            VDP_setTileMapXY(BG_A, TILE_ATTR_FULL(PAL0, 0, FALSE, FALSE, TILE_LOGO_BASE + t), offX + col, offY + row);
        }
    }
}
